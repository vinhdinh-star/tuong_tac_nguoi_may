import sqlite3

def check_database_stats(db_path="quan_ly_kho.db"):
    try:
        conn = sqlite3.connect(db_path)
        cursor = conn.cursor()

        # Lấy danh sách các bảng (trừ bảng hệ thống sqlite_...)
        cursor.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%';")
        tables = [row[0] for row in cursor.fetchall()]

        print(f"=== TỔNG QUAN CƠ SỞ DỮ LIỆU ===")
        print(f"Tổng số bảng: {len(tables)}\n")
        print(f"{'Tên Bảng':<25} | {'Số Cột':<10} | {'Số Dòng (Rows)':<15}")
        print("-" * 55)

        for table in tables:
            # Đếm số lượng cột
            cursor.execute(f"PRAGMA table_info([{table}]);")
            num_columns = len(cursor.fetchall())

            # Đếm số lượng dòng dữ liệu
            cursor.execute(f"SELECT COUNT(*) FROM [{table}];")
            num_rows = cursor.fetchone()[0]

            print(f"{table:<25} | {num_columns:<10} | {num_rows:<15}")

        conn.close()
    except Exception as e:
        print(f"Lỗi khi kết nối database: {e}")

if __name__ == "__main__":
    # Đảm bảo tên file db trùng với file thực tế của bạn (ví dụ: quan_ly_kho.db)
    check_database_stats("quan_ly_kho.db")